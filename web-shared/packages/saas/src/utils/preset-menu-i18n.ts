/**
 * translatePresetMenuName 按 path + 租户名/默认名匹配预置菜单翻译键并渲染；
 * 未命中（企业改写名）时返回原名。供菜单管理页等直接消费。
 * @param path 菜单 path
 * @param name 租户菜单名（可为空）
 * @param defaultName 菜单模板默认名
 */
export function translatePresetMenuName(path: string, name: string, defaultName: string): string | undefined {
  const entries = presetMenuI18n[path];
  const effective = name || defaultName;
  const hit = entries?.find((item) => item.source === effective && item.source === defaultName);
  return hit ? $t(hit.key) : undefined;
}
